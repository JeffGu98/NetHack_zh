#!/usr/bin/env python3
"""Pack Chinese random-text files into the makedefs on-disk format.

Rumors, oracles, engravings, and epitaphs are encrypted with the same
byte cipher as src/hacklib.c xcrypt(). The game decrypts them on read.
Help files are plain text and are not handled here.
"""

from pathlib import Path

DONT_EDIT = "#\tThis data file is generated by 'makedefs'.  Do not edit. \n"
PAD = 60


def xcrypt(data: bytes) -> bytes:
    out = bytearray()
    bitmask = 1
    for ch in data:
        q = ch
        if q & (32 | 64):
            q ^= bitmask
        out.append(q)
        bitmask <<= 1
        if bitmask >= 32:
            bitmask = 1
    return bytes(out)


def pad_line(text: str, pad: int = PAD) -> bytes:
    raw = text.replace("\r", "").replace("\n", "") + "\n"
    data = raw.encode("utf-8")
    if len(data) <= pad:
        body, nl = data[:-1], data[-1:]
        data = body + b"_" * (pad - len(data)) + nl
    return data


def pack_rumors(true_lines: list[str], false_lines: list[str]) -> bytes:
    def section(lines: list[str]) -> bytes:
        return b"".join(xcrypt(pad_line(line)) for line in lines)

    true_b = section(true_lines)
    false_b = section(false_lines)
    # Placeholder sizes; the numeric line's own length depends on the
    # padded fields, which are fixed width, so one pass is enough.
    header = (
        f"{DONT_EDIT}"
        f"{len(true_lines):04d},{len(true_b):06d},000000;"
        f"{len(false_lines):04d},{len(false_b):06d},000000;"
        f"0,0,000000\n"
    ).encode("ascii")
    true_at = len(header)
    false_at = true_at + len(true_b)
    eof_at = false_at + len(false_b)
    header = (
        f"{DONT_EDIT}"
        f"{len(true_lines):04d},{len(true_b):06d},{true_at:06x};"
        f"{len(false_lines):04d},{len(false_b):06d},{false_at:06x};"
        f"0,0,{eof_at:06x}\n"
    ).encode("ascii")
    # Fixed-width fields keep the header length stable.
    if len(header) != true_at:
        raise SystemExit(f"rumor header size changed: {len(header)} != {true_at}")
    return header + true_b + false_b


def pack_oracles(blocks: list[list[str]]) -> bytes:
    """blocks[0] is the special oracle. Each block is a list of lines."""
    body = bytearray()
    starts = []
    for block in blocks:
        body += b"---\n"
        starts.append(len(body))
        for line in block:
            raw = (line + "\n").encode("utf-8")
            if len(raw) >= 80:
                raise SystemExit(f"oracle line exceeds COLNO: {line}")
            body += xcrypt(raw)
    body += b"---\n"
    count = len(blocks)
    # Index is written after we know the text offset.
    index = DONT_EDIT.encode("ascii") + f"{count:5d}\n".encode("ascii")
    index += b"".join(f"{0:05x}\n".encode("ascii") for _ in starts)
    base = len(index)
    index = DONT_EDIT.encode("ascii") + f"{count:5d}\n".encode("ascii")
    index += b"".join(f"{(base + off):05x}\n".encode("ascii") for off in starts)
    if len(index) != base:
        raise SystemExit("oracle index size changed")
    return index + bytes(body)


def pack_rnd(lines: list[str]) -> bytes:
    out = DONT_EDIT.encode("ascii")
    for line in lines:
        out += xcrypt(pad_line(line))
    return out


def main() -> None:
    root = Path(__file__).resolve().parents[1] / "dat" / "locale" / "zh"
    src = root / "src"
    true_lines = [
        line.strip()
        for line in (src / "rumors.tru").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]
    false_lines = [
        line.strip()
        for line in (src / "rumors.fal").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]
    oracle_blocks = []
    block: list[str] = []
    for line in (src / "oracles.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            continue
        if line.startswith("-----"):
            if block:
                oracle_blocks.append(block)
                block = []
            continue
        block.append(line)
    if block:
        oracle_blocks.append(block)
    engrave = [
        line.strip()
        for line in (src / "engrave.txt").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]
    epitaph = [
        line.strip()
        for line in (src / "epitaph.txt").read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ]
    (root / "rumors").write_bytes(pack_rumors(true_lines, false_lines))
    (root / "oracles").write_bytes(pack_oracles(oracle_blocks))
    (root / "engrave").write_bytes(pack_rnd(engrave))
    (root / "epitaph").write_bytes(pack_rnd(epitaph))
    print(
        f"packed rumors {len(true_lines)}+{len(false_lines)}, "
        f"oracles {len(oracle_blocks)}, engrave {len(engrave)}, "
        f"epitaph {len(epitaph)}"
    )


if __name__ == "__main__":
    main()
